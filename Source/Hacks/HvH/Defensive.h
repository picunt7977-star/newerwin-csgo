class EngineInterfaces;
class ClientInterfaces;
struct Memory;

// Дефенсив: окна, в которые сервер не пишет по нам записей лагкомпа. Углы таких тиков враг видит,
// но ни бектрекнуть по ним, ни разрезольвить их не может — туда и уходят скрытые углы AA.
//
// Окно состоит из двух разных частей, и путать их нельзя:
//
//  * тики ВНУТРИ пачки сдвига. Рывок прогоняет заряженные команды подряд, и сервер обрабатывает
//    их за один свой тик, а запись лагкомпа кладёт только по ПОСЛЕДНЕЙ команде пачки. Углы всех
//    предыдущих команд не записываются вовсе — эти тики скрыты на любом сервере, без исключений.
//
//  * тики ПОСЛЕ пачки. Наш m_nTickBase ушёл в будущее, и сервер отбрасывает новые записи по нам,
//    пока не догонит. Это и есть «откат», и он бывает не на каждом сервере: на сборках с
//    DT-фиксом сервер тикбейс не откатывает, и после пачки защиты уже нет.
//
// Поэтому модуль не верит догадкам: он ЗАМЕРЯЕТ откат по m_nTickBase и, пока сервер не подтвердил
// откат, тики после пачки скрытыми не объявляет. Замер идёт непрерывно, а не по дедлайну от каждой
// пачки: пачки идут чаще, чем приходит ответ сервера, и привязанный к ним замер почти никогда не
// доживал до конца (логи 07.11: 279 пачек, 9 удачных замеров). 40 пачек без отката — вердикт
// «сервер не откатывает», и дефенсив перестаёт жечь заряд (с перепроверкой раз в 30 секунд).
//
// Политика окон взята с Neverlose (defensive в Persistence_opensource.lua): заряд копится заранее,
// рывок делается только с полным зарядом и только импульсом — не чаще раза в «интервал» команд,
// а не бесконечным циклом «рывок → зарядка → рывок».
namespace hvh::defensive
{

// Каждый тик из CreateMove, до антиаима и рейджбота
void update(csgo::UserCmd* cmd, const EngineInterfaces& engineInterfaces, const ClientInterfaces& clientInterfaces,
            const Memory& memory) noexcept;

// Сейчас идёт окно: лагкомп по нам сломан, скрытые углы можно показывать
[[nodiscard]] bool windowActive() noexcept;
// Тиков окна осталось (0 — окна нет). Пока сервер не проверен, тики после пачки тут не считаются:
// скрытые углы на непроверенном сервере — это просто наши углы в открытую
[[nodiscard]] int windowLeft() noexcept;
// Длина текущего окна на входе — для режимов «за окно» у скрытых углов
[[nodiscard]] int windowLength() noexcept;
// Номер окна: по нему скрытые углы меняют рисунок от окна к окну
[[nodiscard]] int windowCounter() noexcept;
// Окно подтверждено сервером (откат виден по m_nTickBase), а не только предсказано
[[nodiscard]] bool windowConfirmed() noexcept;

// ---- для меню и индикаторов ----
[[nodiscard]] bool enabled() noexcept;          // включён и может работать (заряд не занят DT)
[[nodiscard]] bool triggerActive() noexcept;    // прямо сейчас есть повод открывать окна
[[nodiscard]] int chargePercent() noexcept;     // 0..100
// Сколько тиков сервер откатывает нам тикбейс на самом деле (выученное). 0 — рывков ещё не было
[[nodiscard]] float measuredRollback() noexcept;
[[nodiscard]] int pulseCount() noexcept;
// Дефенсив сейчас копит чоком, а не пропусками тиков. В этом режиме заряд тикбейса ему не нужен,
// и режим DT «Дефенсив» не делает ничего — индикатор DT это показывает тусклым
[[nodiscard]] bool chargeByChoke() noexcept;

// Что известно про сервер
enum class Verdict {
    Unknown,    // рывков ещё не было или замер не закончен — тики после пачки не объявляем
    RollsBack,  // откат есть: дефенсив работает в полную силу
    Ignores     // откат нулевой (DT-фикс): работают только тики внутри пачки
};
[[nodiscard]] Verdict verdict() noexcept;
// Строка для меню: что модуль делает прямо сейчас и чего ждёт
[[nodiscard]] const char* statusLine() noexcept;

void onRoundStart() noexcept;

// ---- лаг-пик (живёт тут же: ему нужно то же предсказание выхода из-за угла) ----
// Сейчас держим чок на выглядывании
[[nodiscard]] bool lagPeekHolding() noexcept;
[[nodiscard]] int lagPeekCount() noexcept;
[[nodiscard]] const char* lagPeekStatus() noexcept;

}
